import PptxGenJS from "pptxgenjs";
import { resolveDocumentImages } from "./imageResolver.js";

const PptxConstructor = typeof PptxGenJS === "function" ? PptxGenJS : PptxGenJS?.default || PptxGenJS;

const COLORS = {
  primary: "2563EB",
  secondary: "0F172A",
  text: "334155",
  light: "F8FAFC",
  border: "E2E8F0",
  white: "FFFFFF",
  muted: "64748B",
  accent: "F43F5E",
};

export const generatePpt = async (data = {}) => {
  const ppt = new PptxConstructor();
  ppt.layout = "LAYOUT_WIDE";
  ppt.author = data.author || "AgentMesh AI";
  ppt.title = data.title || "Presentation Deck";
  ppt.subject = data.subtitle || data.title || "Presentation Deck";
  ppt.company = "AgentMesh AI";
  ppt.theme = {
    headFontFace: "Arial",
    bodyFontFace: "Arial",
  };

  addCover(ppt, data);

  if (Array.isArray(data?.slides) && data.slides.length > 0) {
    const rawImages = Array.isArray(data?.images) ? data.images : [];
    
    const resolvedImages = await resolveDocumentImages({
      candidateUrls: rawImages,
      topic: data.title || data.subtitle || "Presentation Deck",
      isImageRequested: Boolean(rawImages.length > 0 || data.hasImages),
      maxImages: data.slides.length,
    });

    const validBase64Images = resolvedImages.map((img) => img.base64).filter(Boolean);

    data.slides.forEach((s, i) => {
      const slideImg = validBase64Images.length > 0 ? validBase64Images[i % validBase64Images.length] : null;
      addContentSlide(
        ppt,
        s.title || `Section ${i + 1}`,
        s.points || [],
        i + 1,
        data.slides.length,
        slideImg
      );
    });
  }

  addThankYou(ppt);

  return ppt;
};

export const pptBuffer = async (data = {}) => {
  const ppt = await generatePpt(data);
  const buffer = await ppt.write({ outputType: "nodebuffer" });
  return buffer;
};

const addCover = (ppt, data) => {
  const slide = ppt.addSlide();
  slide.background = {
    color: COLORS.primary,
  };

  slide.addShape(ppt.ShapeType.rect, {
    x: 0,
    y: 0,
    w: 13.33,
    h: 0.18,
    fill: {
      color: "60A5FA",
    },
    line: {
      color: "60A5FA",
    },
  });

  slide.addText(data.title || "Presentation Title", {
    x: 0.7,
    y: 1.8,
    w: 12,
    h: 1.0,
    align: "center",
    color: COLORS.white,
    bold: true,
    fontSize: 28,
  });

  if (data.subtitle) {
    slide.addText(data.subtitle, {
      x: 1,
      y: 3.0,
      w: 11.5,
      h: 0.6,
      align: "center",
      color: "DBEAFE",
      fontSize: 15,
    });
  }

  slide.addText("Generated By AgentMesh AI", {
    x: 0,
    y: 6.8,
    w: 13.33,
    h: 0.3,
    align: "center",
    color: "BFDBFE",
    fontSize: 11,
  });
};

const addContentSlide = (ppt, title, points, index, total, imageBase64 = null) => {
  const slide = ppt.addSlide();

  slide.addShape(ppt.ShapeType.rect, {
    x: 0,
    y: 0,
    w: 13.33,
    h: 0.9,
    fill: {
      color: COLORS.primary,
    },
    line: {
      color: COLORS.primary,
    },
  });

  slide.addText(title, {
    x: 0.8,
    y: 0.18,
    w: 10,
    h: 0.55,
    color: COLORS.white,
    bold: true,
    fontSize: 19,
  });

  slide.addText(`Slide ${index} of ${total}`, {
    x: 11,
    y: 0.28,
    w: 1.8,
    h: 0.3,
    color: "DBEAFE",
    fontSize: 10,
    align: "right",
  });

  const hasImage = Boolean(imageBase64);
  const textWidth = hasImage ? 6.8 : 11.8;

  if (Array.isArray(points) && points.length > 0) {
    const formattedPoints = points.map((p, idx) => ({
      text: typeof p === "string" ? p : String(p?.text || p),
      options: {
        bullet: true,
        fontSize: 14,
        color: COLORS.text,
        breakLine: true,
        spacing: {
          line: 22,
        },
      },
    }));

    slide.addText(formattedPoints, {
      x: 0.8,
      y: 1.4,
      w: textWidth,
      h: 5.0,
      align: "left",
      valign: "top",
    });
  }

  if (hasImage) {
    try {
      slide.addShape(ppt.ShapeType.roundRect, {
        x: 8.0,
        y: 1.35,
        w: 4.6,
        h: 4.8,
        fill: { color: "F1F5F9" },
        line: { color: "CBD5E1", width: 1 },
      });

      slide.addImage({
        data: imageBase64,
        x: 8.1,
        y: 1.45,
        w: 4.4,
        h: 4.5,
        sizing: {
          type: "contain",
          w: 4.4,
          h: 4.5,
        },
      });
    } catch (imgErr) {
      console.warn("[generatePpt] Slide image embedding skipped:", imgErr.message);
    }
  }

  slide.addShape(ppt.ShapeType.line, {
    x: 0.8,
    y: 6.8,
    w: 11.8,
    h: 0,
    line: {
      color: COLORS.border,
      width: 1,
    },
  });

  slide.addText("AgentMesh AI Presentation", {
    x: 0.8,
    y: 6.9,
    w: 6,
    h: 0.3,
    color: COLORS.muted,
    fontSize: 9,
  });
};

